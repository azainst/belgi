def t(lang: str, key: str, **kw) -> str:
    s = T[key].get(lang) or T[key]["ru"]
    return s.format(**kw) if kw else s


def all_langs(key: str) -> set[str]:
    return set(T[key].values())


def notify_text(lang: str, status: str, code: str, deadline: str | None) -> str | None:
    if status not in NOTIFY:
        return None
    d = DEADLINE.get(lang, DEADLINE["ru"]).format(deadline=deadline) if deadline and status == "violation" else ""
    return (NOTIFY[status].get(lang) or NOTIFY[status]["ru"]).format(code=code, d=d)
